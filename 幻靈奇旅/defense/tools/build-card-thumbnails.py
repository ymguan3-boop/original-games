"""Generate defense-only 320px WebP previews, retaining all original card art."""
from pathlib import Path
import json
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[2]
dest = root / 'defense/assets/card-previews'
dest.mkdir(parents=True, exist_ok=True)
manifest = {}
before = after = 0
for spirit, card in json.loads((root / 'data/card-art.json').read_text(encoding='utf-8')).items():
    source = root / card['image'].split('?')[0]
    if not source.is_file():
        raise FileNotFoundError(source)
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image).convert('RGBA')
        image.thumbnail((320, 320), Image.Resampling.LANCZOS)
        target = dest / (spirit + '.webp')
        image.save(target, 'WEBP', quality=82, method=6)
    manifest[spirit] = 'defense/assets/card-previews/' + target.name
    before += source.stat().st_size
    after += target.stat().st_size
(root / 'defense/js/card-previews.js').write_text('/* Generated by tools/build-card-thumbnails.py */\nexport const CARD_PREVIEWS = ' + json.dumps(manifest, ensure_ascii=False) + ';\n', encoding='utf-8')
print(json.dumps({'images':len(manifest), 'originalBytes':before, 'previewBytes':after, 'reductionPercent':round((1-after/before)*100,1)}))
